#[cfg(test)]
mod tests {
    use super::*;
    use crate::diff::{compute_field_cruxes, diff_snapshots};
    use crate::validate::{normalize_and_validate_snapshot, ValidationError};

    #[test]
    fn seed_snapshots_all_validate() {
        let mut bundle = build_seed_bundle();
        for snap in &mut bundle.snapshots {
            assert!(
                normalize_and_validate_snapshot(snap).is_ok(),
                "seed snapshot {} failed validation",
                snap.id
            );
        }
    }

    #[test]
    fn numeric_credence_requires_justification() {
        let bundle = build_seed_bundle();
        let mut snap = bundle.snapshots[0].clone();
        snap.nodes[0].credence = Some(Credence {
            mode: CredenceMode::Numeric,
            band: CredenceBand::High,
            percent: Some(72),
            percent_range: None,
            numeric_rationale: Some("too short".into()),
        });
        let errs = normalize_and_validate_snapshot(&mut snap).unwrap_err();
        assert!(errs
            .iter()
            .any(|e| matches!(e, ValidationError::MissingNumericRationale { .. })));
    }

    #[test]
    fn update_criterion_is_mandatory() {
        let bundle = build_seed_bundle();
        let mut snap = bundle.snapshots[0].clone();
        snap.update_criteria.clear();
        let errs = normalize_and_validate_snapshot(&mut snap).unwrap_err();
        assert!(errs.contains(&ValidationError::MissingUpdateCriterion));
    }

    #[test]
    fn diff_alice_vs_redwood_finds_interp_crux_and_shared_premises() {
        let bundle = build_seed_bundle();
        let alice = bundle.snapshots.iter().find(|s| s.id == "snp_alice_v3").unwrap();
        let redwood = bundle.snapshots.iter().find(|s| s.id == "snp_redwood_v1").unwrap();

        let diff = diff_snapshots(alice, redwood, &bundle.concepts, &bundle.attestations);
        // Shared premises (TAI < 2032, RL scheming [via fork lineage!], Behavioral evals miss scheming)
        assert_eq!(diff.summary.shared_ground_count, 3);
        // Sharpest crux is White-box interp scales (Alice 45% Active vs Redwood 15% Rejected)
        assert!(diff.summary.crux_disagreement_count >= 1);
        assert_eq!(diff.top_cruxes[0].cluster_id, "cpt_interp_scales");
        assert_eq!(diff.summary.premise_bottleneck_overlap_pct, 100);
    }

    #[test]
    fn field_cruxes_surfaces_contested_concepts() {
        let bundle = build_seed_bundle();
        let primary_snaps: Vec<ToCSnapshot> = bundle
            .actors
            .iter()
            .filter_map(|a| {
                a.primary_snapshot_id
                    .as_ref()
                    .and_then(|sid| bundle.snapshots.iter().find(|s| &s.id == sid).cloned())
            })
            .collect();
        let cruxes = compute_field_cruxes(&primary_snaps, &bundle.concepts, &bundle.attestations);
        assert!(!cruxes.is_empty());
        assert!(cruxes.iter().any(|c| c.root_concept_id == "cpt_interp_scales"));
    }
}
