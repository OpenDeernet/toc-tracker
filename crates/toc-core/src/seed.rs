fn c(
    id: &str,
    stage: Stage,
    title: &str,
    description: &str,
    parent: Option<&str>,
    root: &str,
    tags: &[&str],
) -> Concept {
    Concept {
        schema_version: CURRENT_SCHEMA_VERSION,
        id: id.to_string(),
        stage,
        title: title.to_string(),
        description: description.to_string(),
        parent_concept_id: parent.map(str::to_string),
        root_concept_id: root.to_string(),
        tags: tags.iter().map(|s| s.to_string()).collect(),
        created_by_actor_id: None,
        arweave_tx_id: Some(format!("seed_tx_{}", id)),
        created_at: Utc::now() - Duration::days(30),
    }
}

